// CSV export of the data behind the displayed chart, prefixed with
// provenance and methodology comment lines so the file stands on its own.

import { IS_PORTFOLIO, PORTFOLIO_DISCLOSURE, T } from "./edition.js";

const DATA_NOTE = IS_PORTFOLIO
  ? "Data: synthetic demo dataset generated by portfolio/scripts/generate-synthetic.mjs (fixed seed). These are not historical market observations and not research results. Not investment advice."
  : "Data: research edition (not included in this repository). Not investment advice.";

function cell(value) {
  if (value === null || value === undefined || (typeof value === "number" && !Number.isFinite(value))) return "";
  const s = String(value);
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

const comment = (text) => `# ${String(text).replace(/\r?\n/g, " ")}`;

/**
 * @param {object} spec
 * @param {string} spec.title
 * @param {Record<string, string|number>} spec.config  analysis parameters
 * @param {string} spec.status  research status label
 * @param {string[]} spec.notes  status reasons, sources and methodology
 * @param {{key: string, label: string}[]} spec.columns
 * @param {object[]} spec.rows
 * @param {string} spec.generatedAt  ISO timestamp
 */
export function toCsv({ title, config, status, notes = [], columns, rows, generatedAt }) {
  const lines = [
    ...(IS_PORTFOLIO ? [comment(PORTFOLIO_DISCLOSURE)] : []),
    comment(title),
    comment(`Generated ${generatedAt} by the Digital Gold Asset Relationship Explorer`),
    comment(`${T.statusField}: ${status}`),
    ...Object.entries(config).map(([k, v]) => comment(`${k}: ${v}`)),
    ...notes.map(comment),
    comment(DATA_NOTE),
    columns.map((c) => cell(c.label)).join(","),
    ...rows.map((r) => columns.map((c) => cell(r[c.key])).join(",")),
  ];
  return `${lines.join("\n")}\n`;
}

/** Browser download of a CSV string. */
export function downloadCsv(filename, csv) {
  const url = URL.createObjectURL(new Blob([csv], { type: "text/csv;charset=utf-8" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}
